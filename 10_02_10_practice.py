# 실습 4. 이상 센서 필터링하기

import numpy as np

# 조건에 맞는 이상 센서값만 불리언 인덱식으로 선별

# 회전수와 토크 배열 준비
rpm4 = np.array([1551, 1408, 1498, 2861, 1444, 1400])
torque4 = np.array([42.8, 46.3, 49.4, 4.4, 41.9, 66.6])

# 비교 연산으로 회전수가 기준을 넘는 조건 생성 -> 2000 이상
print(rpm4[rpm4 > 2000 | (torque4 < 10)]) # 2861

# 다중 조건으로 회전수 과다 또는 토크 과소 위험 시점 필터링
# -> rpm[0]과 torque[0] 데이터는 같은 시기의 상황을 다룬다


