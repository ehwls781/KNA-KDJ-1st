# 실습 5. 조건별 개수와 비율 세기
# 조건을 만족하는 값의 개수와 전체 대비 비율 계산

# 토크 배열 준비
torque5 = np.array([42.8, 46.3, 49.4, 4.4, 41.9, 66.6])

# 비교 조건으로 참.거짓 불리언 배열 생성
high5 = torque5 > 50
print(high5) # [False False False False False  True]

print(torque5[torque5> 50]) # [66.6]

# 불리언 배열의 합(sum)으로 개수, 
# 평균(mean)으로 비율 계산
print(high5.sum()) # 1
# True = 1 , False = 0 
print(round(high5.mean(), 2)) # 0.17 -> 소수점 이하 2자리까지 나오게 처리

