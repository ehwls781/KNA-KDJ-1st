# 리스트 심화 정렬
# 리스트.sort()
# 데이터를 정렬
# 오름차순 ( 작은 숫자부터 큰 숫자까지 )
# 내림차순으로 정렬하고 싶을 때는 .sort(reverse=True)

n = [37, 2, 8, 100, 1004, -1, 22]
print("n 리스트 원본:", n)

# 오름차순 정렬
n.sort()
print("n 리스트 오름차순 정렬:", n) # [-1, 2, 8, 22, 37, 100, 1004]

# 내림차순 정렬
n.sort(reverse = True)
print("n 리스트 내림차순 정렬:", n) # [1004, 100, 37, 22, 8, 2, -1]

# 리스트 순서 뒤집기
# 값의 크기대로 정렬은 하지 않고 지금 순서 그대로 뒤집기
# reverse()

n.reverse()
print("n 리스트 뒤집기 정렬:", n) # [-1, 2, 8, 22, 37, 100, 1004]

