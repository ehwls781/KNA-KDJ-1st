# 원본 리스트를 복사해서 리스트 수정 진행
# nums = [1, 2, 3, 4, 5, 999] <- 원본
new_nums = nums # 스스로의 메모리를 할당받지 않고, 주소만 복사
print(new_nums) # [1, 2, 3, 4, 5, 999]

